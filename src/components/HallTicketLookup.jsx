import React, { useState } from 'react';
import { canAccessHallTicket } from '../utils/hallTicket';
import '../styles/HallTicket.css';

const HallTicketLookup = ({ onFound }) => {
  const [applicationId, setApplicationId] = useState('');
  const [mobile, setMobile] = useState('');
  const [status, setStatus] = useState('idle');
  const [foundApplication, setFoundApplication] = useState(null);
  const [error, setError] = useState('');

  const statusClassMap = {
    Submitted: 'submitted',
    'Under Review': 'under-review',
    'Additional Information Required': 'additional-info',
    Approved: 'approved',
    Rejected: 'rejected',
    'Hall Ticket Generated': 'ticket-generated',
    'Hall Ticket Reissued': 'ticket-generated',
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    setError('');
    setFoundApplication(null);

    const trimmedId = applicationId.trim();
    const trimmedMobile = mobile.trim();

    if (!trimmedId.startsWith('BSA-')) {
      setError('Application ID must start with "BSA-".');
      setStatus('error');
      return;
    }

    if (!/^\d{10}$/.test(trimmedMobile)) {
      setError('Mobile number must be exactly 10 digits.');
      setStatus('error');
      return;
    }

    setStatus('loading');

    try {
      const stored = JSON.parse(localStorage.getItem('sparkids_applications') || '[]');
      if (!Array.isArray(stored)) {
        throw new Error('Stored applications must be an array.');
      }
      const match = stored.find(
        (app) => app.applicationId === trimmedId && app.mobile === trimmedMobile
      );

      if (match) {
        if (canAccessHallTicket(match)) {
          setFoundApplication(match);
          setStatus('found');
          if (onFound) onFound(match);
          return;
        }

        if (match.status === 'Rejected') {
          setError(match.candidateMessage || 'Your application was not approved. Please contact the academy for assistance.');
          setStatus('rejected');
          return;
        }

        if (match.status === 'Additional Information Required') {
          setError(match.candidateMessage || 'Additional information is required. Please contact the academy for next steps.');
          setStatus('additional-info');
          return;
        }

        if (match.status === 'Hall Ticket Cancelled') {
          setError('This hall ticket has been cancelled. Please contact the academy for assistance.');
          setStatus('cancelled');
          return;
        }
        setStatus('pending');
        return;
      }
    } catch (err) {
      console.error('localStorage read error:', err);
      setError('The application lookup could not be completed. Please try again or contact the academy.');
      setStatus('error');
      return;
    }

    setStatus('not-found');
  };

  return (
    <div className="lookup-card">
      <h2>Hall Ticket Lookup</h2>

      <form onSubmit={handleSubmit} noValidate>
        <div className="form-group">
          <label className="form-label">Application ID</label>
          <input
            type="text"
            className="form-input"
            placeholder="e.g. BSA-2025-123456"
            value={applicationId}
            onChange={(e) => {
              setApplicationId(e.target.value);
              setStatus('idle');
              setError('');
            }}
          />
        </div>

        <div className="form-group">
          <label className="form-label">Registered Mobile Number</label>
          <input
            type="tel"
            className="form-input"
            placeholder="10-digit mobile number"
            maxLength={10}
            value={mobile}
            onChange={(e) => {
              setMobile(e.target.value);
              setStatus('idle');
              setError('');
            }}
          />
        </div>

        <button type="submit" className="submit-btn" disabled={status === 'loading'}>
          {status === 'loading' ? 'Searching...' : 'Find Hall Ticket'}
        </button>
      </form>

      {/* Status Messages */}
      {status === 'error' && (
        <div className="status-message" style={{ color: 'var(--primary-orange)' }}>
          ❌ {error}
        </div>
      )}

      {status === 'pending' && (
        <div className="status-message pending">
          ⏳ Your application is being processed. A hall ticket is available after it has been
          approved and generated by the academy.
        </div>
      )}

      {status === 'not-found' && (
        <div className="status-message warning" role="status">
          No matching application was found. Check the Application ID and registered mobile number,
          or contact the academy.
        </div>
      )}

      {['rejected', 'additional-info', 'cancelled'].includes(status) && (
        <div className={`status-message ${status === 'additional-info' ? 'warning' : 'error'}`} role="alert">
          {error}
        </div>
      )}

      {status === 'found' && foundApplication && (
        <div className="status-message approved">
          <p>✅ Application found!</p>
          <div className="ht-found-summary">
            <p>
              <strong>Name:</strong> {foundApplication.candidateName}
            </p>
            <p>
              <strong>Course:</strong> {foundApplication.course}
            </p>
            <p>
              <strong>Exam:</strong> {foundApplication.examName} on{' '}
              {new Date(foundApplication.examDate).toLocaleDateString()}
            </p>
            <p>
              <strong>Status:</strong>{' '}
              <span
                className={`ht-status-badge ${statusClassMap[foundApplication.status] || 'submitted'}`}
              >
                {foundApplication.status}
              </span>
            </p>
          </div>
        </div>
      )}
    </div>
  );
};

export default HallTicketLookup;
