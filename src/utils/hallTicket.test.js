import {
  canAccessHallTicket,
  createHallTicketNumber,
  parseExamSessions,
  withStatusHistory,
} from './hallTicket';

describe('hall ticket workflow', () => {
  test('only generated or reissued tickets are available to candidates', () => {
    expect(canAccessHallTicket({ status: 'Submitted' })).toBe(false);
    expect(canAccessHallTicket({ status: 'Approved' })).toBe(false);
    expect(canAccessHallTicket({
      status: 'Hall Ticket Generated',
      hallTicketNumber: '',
    })).toBe(false);
    expect(canAccessHallTicket({ status: 'Hall Ticket Cancelled' })).toBe(false);
    expect(canAccessHallTicket({
      status: 'Hall Ticket Generated',
      hallTicketNumber: 'HT-BSA-2026-123456-V1',
    })).toBe(true);
    expect(canAccessHallTicket({
      status: 'Hall Ticket Reissued',
      hallTicketNumber: 'HT-BSA-2026-123456-V2',
    })).toBe(true);
  });

  test('creates a hall-ticket number linked to its application', () => {
    expect(createHallTicketNumber('BSA-2026-123456', 2)).toBe(
      'HT-BSA-2026-123456-V2'
    );
  });

  test('records status changes without discarding existing history', () => {
    const initial = {
      applicationId: 'BSA-2026-123456',
      status: 'Approved',
      statusHistory: [{ status: 'Submitted', changedAt: '2026-01-01T00:00:00.000Z' }],
    };

    const updated = withStatusHistory(initial, 'Hall Ticket Generated', {
      hallTicketNumber: 'HT-BSA-2026-123456-V1',
      historyDetails: { note: 'Ticket generated by admin' },
    });

    expect(updated.status).toBe('Hall Ticket Generated');
    expect(updated.hallTicketNumber).toBe('HT-BSA-2026-123456-V1');
    expect(updated.statusHistory).toHaveLength(2);
    expect(updated.statusHistory[1].status).toBe('Hall Ticket Generated');
    expect(updated.statusHistory[1].note).toBe('Ticket generated by admin');
    expect(updated.updatedAt).toBe(updated.statusHistory[1].changedAt);
  });

  test('rejects malformed exam session storage', () => {
    expect(parseExamSessions('[{"sessionId":"EXAM-1"}]')).toHaveLength(1);
    expect(() => parseExamSessions('{"sessionId":"EXAM-1"}')).toThrow(
      'Stored exam sessions must be an array.'
    );
  });
});
